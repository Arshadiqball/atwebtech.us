<h2>Step 2: Match metrics to the goal</h2>

<h3>For awareness</h3>
<p><strong>Reach</strong> (how many different people saw your content) and <strong>follower growth</strong> over time are the clearest signals. Shares are also useful, because each share puts you in front of someone new.</p>

<h3>For community</h3>
<p>Look at <strong>comments</strong>, <strong>replies</strong>, and <strong>saves</strong>. These take more effort than a like, so they suggest that people genuinely value what you post. Your own response rate to comments matters here too.</p>

<h3>For traffic</h3>
<p><strong>Link clicks</strong> and <strong>profile visits</strong> are the core numbers. Pair them with your website analytics, so you can see what people did after they arrived.</p>

<h3>For conversion</h3>
<p>Track <strong>sign-ups, enquiries, or sales</strong> that you can attribute to social, for example by using tagged links or asking new customers how they found you. Engagement numbers alone cannot tell you this.</p>

<h2>Step 3: Use rates, not just totals</h2>
<p>Totals naturally rise as your audience grows, which can hide whether content is actually improving. Rates help you compare fairly:</p>
<ul>
  <li><strong>Engagement rate:</strong> engagements divided by reach (or by followers), shown as a percentage.</li>
  <li><strong>Click-through rate:</strong> link clicks divided by reach.</li>
</ul>
<p>Platforms calculate these differently, so compare a channel with itself over time rather than comparing one platform's rate directly with another's.</p>

<h2>Step 4: Be careful with vanity metrics</h2>
<p>Likes and follower counts feel good, but on their own they rarely explain whether social media is helping. A post with fewer likes but many saves and clicks may be doing more for your goal than a popular post that nobody acts on.</p>
